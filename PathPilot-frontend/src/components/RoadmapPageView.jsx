/**
 * RoadmapPageView.jsx — "My Roadmap" full-page view.
 *
 * Lets the user choose a goal and see the full React Flow graph.
 * Clearly labelled as a sample preview separate from the C++ output.
 */
import { Brain, Code2, Trophy, Info } from 'lucide-react';
import RoadmapView from './RoadmapView';
import { GOALS } from '../data/courseData';

const ICON_MAP = { Brain, Code2, Trophy };

const THEME = {
  purple: { pillCls: 'pill-purple', iconBg: 'rgba(139,124,255,0.15)', iconColor: '#8B7CFF' },
  blue:   { pillCls: 'pill-blue',   iconBg: 'rgba(89,184,255,0.12)',  iconColor: '#59B8FF' },
  green:  { pillCls: 'pill-green',  iconBg: 'rgba(82,217,164,0.12)',  iconColor: '#52D9A4' },
};

export default function RoadmapPageView({ selectedGoalId, onGoalSelect }) {
  return (
    <div className="view-wrap">
      <h1 className="view-heading">My Roadmap</h1>
      <p className="view-sub">
        Select a goal to explore its prerequisite graph.
      </p>

      {/* Goal selector tabs */}
      <div style={{ display: 'flex', gap: 10, flexWrap: 'wrap', marginBottom: 24 }}>
        {GOALS.map(g => {
          const Icon  = ICON_MAP[g.icon] ?? Brain;
          const theme = THEME[g.bgToken] ?? THEME.purple;
          const active = selectedGoalId === g.id;
          return (
            <button
              key={g.id}
              id={`roadmap-tab-${g.id}`}
              className={`btn ${active ? 'btn-outline-accent' : 'btn-ghost'}`}
              style={active ? { borderColor: `${g.accentColor}55`, color: g.accentColor, background: `${g.accentColor}14` } : {}}
              onClick={() => onGoalSelect(g.id)}
            >
              <Icon size={14} strokeWidth={2} />
              {g.shortTitle}
            </button>
          );
        })}
      </div>

      {/* Graph panel */}
      <div className="roadmap-section">
        {/* Sample disclaimer */}
        <div className="sample-banner">
          <Info size={12} />
          <span>
            <strong>Sample preview</strong> — this graph is illustrative.
            The actual prerequisite roadmap will be generated by the C++ algorithm backend.
          </span>
        </div>

        {selectedGoalId && (
          <div className="roadmap-header">
            <div className="roadmap-title-row">
              <h2>
                {GOALS.find(g => g.id === selectedGoalId)?.title ?? ''} — Prerequisite Graph
              </h2>
            </div>
            <div className="roadmap-actions">
              <button
                id="btn-clear-roadmap"
                className="btn btn-ghost"
                style={{ fontSize: '0.78rem', padding: '6px 12px' }}
                onClick={() => onGoalSelect(null)}
              >
                Clear
              </button>
            </div>
          </div>
        )}

        <div className="roadmap-body">
          <RoadmapView
            goalId={selectedGoalId}
            onSelectGoal={() => {}}
          />
        </div>
      </div>
    </div>
  );
}
